"""Temporary loopback service for /phone chat before the next backend promotion.

It does not own authentication or secrets: every request is verified against the
running IZO backend and the answer is generated by the configured local Ollama
gateway. The canonical endpoint lives in main.py and replaces this sidecar after
the next normal release promotion.
"""

from __future__ import annotations

import asyncio
import os
import re
from typing import Literal

import httpx
from fastapi import FastAPI, HTTPException, Request
from pydantic import BaseModel, Field


BACKEND_URL = os.getenv("IZO_BACKEND_URL", "http://127.0.0.1:8000").rstrip("/")
OLLAMA_URL = os.getenv("OLLAMA_BASE_URL", "http://127.0.0.1:11434").rstrip("/")
CHAT_MODEL = os.getenv("PHONE_CHAT_MODEL", "gemma4:31b-cloud").strip()
ALLOWED_ORIGINS = {"https://izo.alikinas.ru", "http://127.0.0.1:5173", "http://localhost:5173"}
SYSTEM_PROMPT = (
    "Ты — помощник ИЗО АСА. Отвечай по-русски, понятно и по существу. "
    "Помогай формулировать идеи для изображений, видео и публикаций, но не утверждай, "
    "что файл или генерация уже созданы, если ты вернул только текст."
)


class ChatTurn(BaseModel):
    role: Literal["user", "assistant"]
    content: str = Field(min_length=1, max_length=4000)


class ChatRequest(BaseModel):
    messages: list[ChatTurn] = Field(min_length=1, max_length=20)
    route: Literal["auto", "local", "api"] = "auto"
    images: list[str] = Field(default_factory=list, max_length=4)


app = FastAPI(docs_url=None, redoc_url=None, openapi_url=None)
chat_slots = asyncio.Semaphore(max(1, min(8, int(os.getenv("PHONE_CHAT_CONCURRENCY", "3")))))


async def authenticated(request: Request) -> bool:
    cookie = request.headers.get("cookie", "")
    if not cookie:
        return False
    async with httpx.AsyncClient(timeout=5) as client:
        response = await client.get(
            f"{BACKEND_URL}/api/me-v2",
            headers={"cookie": cookie, "user-agent": request.headers.get("user-agent", "IZO phone")},
        )
    return response.status_code == 200


def image_payloads(values: list[str]) -> list[str]:
    if sum(len(value) for value in values) > 12_000_000:
        raise HTTPException(413, "Вложения чата слишком большие.")
    result: list[str] = []
    for value in values:
        match = re.fullmatch(r"data:image/(?:jpeg|jpg|png|webp);base64,([A-Za-z0-9+/=\r\n]+)", value.strip(), flags=re.IGNORECASE)
        if not match:
            raise HTTPException(400, "Чат принимает изображения JPEG, PNG или WebP.")
        result.append(re.sub(r"\s+", "", match.group(1)))
    return result


@app.get("/health")
async def health() -> dict[str, bool]:
    return {"ok": True}


@app.post("/chat")
async def chat(payload: ChatRequest, request: Request) -> dict[str, object]:
    origin = request.headers.get("origin", "")
    if origin and origin not in ALLOWED_ORIGINS:
        raise HTTPException(403, "Источник запроса не разрешён.")
    if not await authenticated(request):
        raise HTTPException(401, "Войдите в аккаунт, чтобы открыть чат.")
    if payload.messages[-1].role != "user":
        raise HTTPException(400, "Последним должно быть сообщение пользователя.")
    messages: list[dict[str, object]] = [{"role": "system", "content": SYSTEM_PROMPT}]
    messages.extend({"role": turn.role, "content": turn.content.strip()} for turn in payload.messages[-20:])
    images = image_payloads(payload.images)
    if images:
        messages[-1]["images"] = images
    body = {
        "model": CHAT_MODEL,
        "stream": False,
        "think": False,
        "keep_alive": -1,
        "messages": messages,
        "options": {"temperature": 0.45, "num_predict": 1000, "num_ctx": 16384},
    }
    try:
        async with chat_slots:
            async with httpx.AsyncClient(timeout=120) as client:
                response = await client.post(f"{OLLAMA_URL}/api/chat", json=body)
            if response.status_code >= 400:
                raise RuntimeError(f"status={response.status_code}")
            data = response.json()
            reply = str((data.get("message") or {}).get("content") or "").strip()
            if not reply:
                raise RuntimeError("empty response")
    except (httpx.HTTPError, RuntimeError, ValueError) as exc:
        raise HTTPException(502, "Чат временно недоступен. Повторите позже или обратитесь в поддержку.") from exc
    return {"ok": True, "reply": reply[:8000], "provider": "local", "model": "ИЗО Чат", "usage": data.get("usage") or {}}
