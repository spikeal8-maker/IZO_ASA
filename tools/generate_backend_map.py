"""Generate a lightweight navigation and route/auth map for backend/main.py.

The script parses source with the standard-library AST and never imports the
application, so it cannot open the live database or start background workers.
"""

from __future__ import annotations

import argparse
import ast
from dataclasses import dataclass
from pathlib import Path


HTTP_METHODS = {"get", "post", "put", "patch", "delete", "options", "head"}
AUTH_CALLS = {
    "require_trusted_admin": "admin",
    "require_trusted_user": "user",
    "resolve_trusted_user": "user",
    "resolve_auth_session_from_request": "session",
}


@dataclass(frozen=True)
class Symbol:
    kind: str
    name: str
    start: int
    end: int


@dataclass(frozen=True)
class Route:
    method: str
    path: str
    handler: str
    line: int
    auth: str


def dotted_name(node: ast.AST) -> str:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        prefix = dotted_name(node.value)
        return f"{prefix}.{node.attr}" if prefix else node.attr
    return ""


def literal_string(node: ast.AST | None) -> str:
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    return "<dynamic>"


def called_names(node: ast.AST) -> set[str]:
    result: set[str] = set()
    for child in ast.walk(node):
        if isinstance(child, ast.Call):
            name = dotted_name(child.func)
            if name:
                result.add(name.rsplit(".", 1)[-1])
    return result


def infer_auth(function: ast.FunctionDef | ast.AsyncFunctionDef, path: str) -> str:
    calls = called_names(function)
    for call, policy in AUTH_CALLS.items():
        if call in calls:
            return policy
    if path.endswith("/telegram/webhook"):
        return "webhook: telegram secret required"
    if path.endswith("/max/webhook"):
        return "webhook: MAX secret conditional"
    if path.startswith("/api/admin/"):
        return "REVIEW: admin route without detected gate"
    if any(marker in path for marker in ("/send-message", "/set-webhook", "/delete-webhook", "/poll-once", "/configure-bot")):
        return "REVIEW: operational route without detected gate"
    return "public/optional/review"


def parse_source(source_path: Path) -> tuple[list[Symbol], list[Route]]:
    tree = ast.parse(source_path.read_text(encoding="utf-8"), filename=str(source_path))
    symbols: list[Symbol] = []
    routes: list[Route] = []

    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            kind = "async function" if isinstance(node, ast.AsyncFunctionDef) else "function"
            symbols.append(Symbol(kind, node.name, node.lineno, node.end_lineno or node.lineno))
            for decorator in node.decorator_list:
                if not isinstance(decorator, ast.Call):
                    continue
                decorator_name = dotted_name(decorator.func)
                if not decorator_name.startswith("app."):
                    continue
                method = decorator_name.rsplit(".", 1)[-1].lower()
                if method not in HTTP_METHODS:
                    continue
                path = literal_string(decorator.args[0] if decorator.args else None)
                routes.append(Route(method.upper(), path, node.name, node.lineno, infer_auth(node, path)))
        elif isinstance(node, ast.ClassDef):
            symbols.append(Symbol("class", node.name, node.lineno, node.end_lineno or node.lineno))

    return symbols, routes


def render(source_path: Path, symbols: list[Symbol], routes: list[Route]) -> str:
    functions = [symbol for symbol in symbols if symbol.kind.endswith("function")]
    classes = [symbol for symbol in symbols if symbol.kind == "class"]
    lines = [
        "# Backend symbol and route map",
        "",
        "Generated by `python tools/generate_backend_map.py` using AST only. Do not edit manually.",
        "",
        f"Source: `{source_path.as_posix()}`",
        "",
        "## Summary",
        "",
        f"- Functions: {len(functions)}",
        f"- Classes: {len(classes)}",
        f"- Routes: {len(routes)}",
        "",
        "Auth policy is a conservative static hint. Every `REVIEW` row must be checked in code and tests.",
        "",
        "## Routes and detected authorization",
        "",
        "| Method | Path | Handler | Line | Detected policy |",
        "|---|---|---|---:|---|",
    ]
    for route in routes:
        path = route.path.replace("|", "\\|")
        policy = route.auth.replace("|", "\\|")
        lines.append(f"| {route.method} | `{path}` | `{route.handler}` | {route.line} | {policy} |")

    lines.extend(
        [
            "",
            "## Classes",
            "",
            "| Name | Lines |",
            "|---|---:|",
        ]
    )
    for symbol in classes:
        lines.append(f"| `{symbol.name}` | {symbol.start}–{symbol.end} |")

    lines.extend(
        [
            "",
            "## Functions",
            "",
            "| Name | Kind | Lines |",
            "|---|---|---:|",
        ]
    )
    for symbol in functions:
        lines.append(f"| `{symbol.name}` | {symbol.kind} | {symbol.start}–{symbol.end} |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, default=Path("backend/main.py"))
    parser.add_argument("--output", type=Path, default=Path("backend/SYMBOL_MAP.md"))
    parser.add_argument("--check", action="store_true", help="Fail if the generated output differs from the file.")
    args = parser.parse_args()

    symbols, routes = parse_source(args.source)
    rendered = render(args.source, symbols, routes)
    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if current != rendered:
            print(f"outdated: {args.output}")
            return 1
        print(f"ok: {args.output}")
        return 0

    args.output.write_text(rendered, encoding="utf-8")
    print(f"wrote {args.output}: {len(symbols)} symbols, {len(routes)} routes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
